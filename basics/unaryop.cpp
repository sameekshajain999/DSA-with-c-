#include<iostream>
using namespace std;
int main(){
    int a=4;
    cout<<a;
    cout<<endl;
    //pre increment operator
    cout<<(++a)<<endl;
    cout<< "pre increment:"<<a<<endl;
    // post decrement operator
    cout<<(a++)<<endl;
    cout<<"post increment:"<<a<<endl;
    //pre decrementt
     cout<<"pre  decrement:"<<a<<endl;
    cout<<(--a)<<endl;
    
    //post decrement
    cout<<(a--)<<endl;
    cout<<"post decrement:"<<a<<endl;

}